function norm(text) {
  return ' ' + text.toLowerCase().replace(/ё/g, 'е').replace(/[^a-zа-я0-9\s-]/g, ' ').replace(/\s+/g, ' ') + ' ';
}

function score(t, list) {
  let s = 0;
  const hits = [];
  for (const [stem, w] of list) {
    const st = stem.replace(/ё/g, 'е');
    // Ищем основу в начале слова (или фразу целиком)
    const re = new RegExp('(^|\\s)' + st.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'g');
    const m = t.match(re);
    if (m) { s += w * Math.min(m.length, 3); hits.push(stem.trim()); }
  }
  return { s, hits };
}

function pickKey(t, dict) {
  let best = null, bestN = 0;
  for (const [k, stems] of Object.entries(dict)) {
    let n = 0;
    for (const st of stems) if (t.includes(' ' + st.replace(/ё/g, 'е'))) n++;
    if (n > bestN) { bestN = n; best = k; }
  }
  return best;
}

function firstMatch(t, table) {
  let bestIdx = Infinity, best = null;
  for (const [stem, phrase] of table) {
    const i = t.indexOf(' ' + stem.replace(/ё/g, 'е'));
    if (i >= 0 && i < bestIdx) { bestIdx = i; best = phrase; }
  }
  return best;
}

function seasonFromDate(dateStr) {
  const m = new Date(dateStr || Date.now()).getMonth();
  if (m === 11 || m <= 1) return 'winter';
  if (m <= 4) return 'spring';
  if (m <= 7) return 'summer';
  return 'autumn';
}

// Сигмоида: превращаем разницу «за» и «против» в число 0..1
const squash = (x, k = 0.9) => 1 / (1 + Math.exp(-k * x));

export function analyzeText(text, dateStr) {
  const t = norm(text || '');
  const words = t.trim().split(' ').filter(Boolean).length;

  const pos = score(t, LEX.positive), neg = score(t, LEX.negative);
  const eh = score(t, LEX.energyHigh), el = score(t, LEX.energyLow);
  const wm = score(t, LEX.warm), cd = score(t, LEX.cold);
  const so = score(t, LEX.social), al = score(t, LEX.alone);
  const no = score(t, LEX.nostalgia), te = score(t, LEX.tension);

  // Восклицания добавляют энергии, многоточия — задумчивости
  const excl = (text.match(/!/g) || []).length;
  const dots = (text.match(/\.\.\.|…/g) || []).length;

  const valence = clamp(squash(pos.s - neg.s * 1.1 - te.s * 0.45 + excl * 0.15));
  const energy = clamp(squash(eh.s - el.s + excl * 0.35 - dots * 0.3, 0.8));
  const warmth = clamp(squash(wm.s - cd.s));
  const social = clamp(squash(so.s - al.s * 1.2, 1.1));
  const nostalgia = clamp(1 - Math.exp(-0.6 * (no.s + dots * 0.4)));
  const tension = clamp(1 - Math.exp(-0.55 * te.s));

  const season = pickKey(t, SEASONS) || seasonFromDate(dateStr);
  const timeOfDay = pickKey(t, TIMES) || 'day';
  const place = firstMatch(t, PLACES);
  const detail = firstMatch(t, DETAILS);

  const title = makeTitle({ season, timeOfDay, place, detail, seasonExplicit: !!pickKey(t, SEASONS) });
  const caption = pickCaption(text);

  return {
    source: 'rules',
    axes: { valence, energy, warmth, social, nostalgia, tension },
    season, timeOfDay, place, detail,
    title, caption,
    keywords: {
      positive: pos.hits, negative: neg.hits, energyHigh: eh.hits, energyLow: el.hits,
      warm: wm.hits, cold: cd.hits, nostalgia: no.hits, tension: te.hits,
    },
    words,
  };
}

// Правило названий: 3–7 слов, «время/сезон + место + деталь», без слов-эмоций.
export function makeTitle({ season, timeOfDay, place, detail, seasonExplicit }) {
  const tn = TIME_NOUN[timeOfDay] || TIME_NOUN.day;
  const parts = [];
  // Сезон в начале, если он есть в тексте или иначе название получится слишком коротким
  const needSeason = seasonExplicit || !place || !detail;
  if (needSeason && SEASON_ADJ[season]) parts.push(SEASON_ADJ[season][tn.g], tn.word.toLowerCase());
  else parts.push(tn.word);
  if (place) parts.push(place);
  if (detail && !(place && detail.includes(place.split(' ').pop()))) parts.push(detail);
  let title = parts.join(' ');
  let n = title.split(' ').length;
  if (n < 3) title += ' без спешки';
  n = title.split(' ').length;
  if (n > 7) title = title.split(' ').slice(0, 7).join(' ');
  return title.charAt(0).toUpperCase() + title.slice(1);
}

// Подпись: самая «чувственная» короткая фраза из текста пользователя
const SENSORY = ['пах', 'запах', 'свет', 'звук', 'тепл', 'холод', 'ветер', 'солн', 'дожд', 'снег',
  'тих', 'смея', 'вкус', 'цвет', 'жёлт', 'желт', 'небо', 'огн', 'музык', 'голос'];

export function pickCaption(text) {
  const sentences = (text || '')
    .split(/(?<=[.!?…])\s+|\n+/)
    .map((s) => s.trim())
    .filter((s) => s.length > 8);
  if (!sentences.length) return (text || '').slice(0, 80);
  let best = sentences[0], bestScore = -1;
  for (const s of sentences) {
    const low = s.toLowerCase();
    let sc = SENSORY.reduce((a, w) => a + (low.includes(w) ? 1 : 0), 0);
    sc -= Math.max(0, s.length - 90) / 40; // длинные фразы хуже читаются на карточке
    if (sc > bestScore) { bestScore = sc; best = s; }
  }
  if (best.length > 96) {
    const cut = best.slice(0, 96);
    best = cut.slice(0, cut.lastIndexOf(' ')) + '…';
  }
  return best.replace(/[.]$/, '');
}
